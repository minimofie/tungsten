#!/usr/bin/env python3
"""Builds Tungsten/base/data/api.luau from a Roblox API dump
(Mini-API-Dump.json or Full-API-Dump.json, as published for each client
version). Run it when the bundled data gets old:

    python3 tools/make_api.py <path to API-Dump.json> Tungsten/base/data/api.luau [client version]

The output is a Luau module with one compact string per class, decoded by
base/explorer/api.luau when a class is first needed:

    Classes[name] = "Superclass|class tags|prop;prop;..."
    class tags: N not creatable, S service, D deprecated, B not browsable
    prop = "Name,Type,Category index,flags"
    Type: b boolean, f float, d double, i int, l int64, s string,
          a DataType name (Vector3, CFrame, ...), E:Enum name, C:Class name
    flags: r read only, d deprecated, h hidden, n not scriptable,
           w write only, p plugin security, R roblox script security,
           L local user security, W writing needs more than reading
Properties nobody can read from a script (RobloxSecurity,
NotAccessibleSecurity) are left out.
"""
import json
import sys

READABLE = {"None": "", "PluginSecurity": "p", "LocalUserSecurity": "L", "RobloxScriptSecurity": "R"}
RANK = {"None": 0, "PluginSecurity": 1, "LocalUserSecurity": 2, "RobloxScriptSecurity": 3, "RobloxSecurity": 4, "NotAccessibleSecurity": 5}
PRIMITIVE = {"bool": "b", "float": "f", "double": "d", "int": "i", "int64": "l", "string": "s"}


def lua_string(text):
    out = ['"']
    for ch in text:
        if ch in '"\\':
            out.append("\\" + ch)
        elif ch == "\n":
            out.append("\\n")
        elif ord(ch) < 32 or ord(ch) > 126:
            out.append("\\%d" % ord(ch) if ord(ch) < 256 else ch)
        else:
            out.append(ch)
    out.append('"')
    return "".join(out)


def main(source, target, client=None):
    with open(source, encoding="utf-8") as handle:
        dump = json.load(handle)
    categories = []
    category_index = {}
    classes = {}
    for cls in dump["Classes"]:
        tags = [t for t in cls.get("Tags", []) if isinstance(t, str)]
        ctags = ""
        ctags += "N" if "NotCreatable" in tags else ""
        ctags += "S" if "Service" in tags else ""
        ctags += "D" if "Deprecated" in tags else ""
        ctags += "B" if "NotBrowsable" in tags else ""
        props = []
        for member in cls["Members"]:
            if member["MemberType"] != "Property":
                continue
            security = member.get("Security", {"Read": "None", "Write": "None"})
            if isinstance(security, str):
                security = {"Read": security, "Write": security}
            read, write = security["Read"], security["Write"]
            if read not in READABLE:
                continue
            mtags = [t for t in member.get("Tags", []) if isinstance(t, str)]
            value = member["ValueType"]
            kind = value["Category"]
            if kind == "Primitive":
                code = PRIMITIVE.get(value["Name"], "s")
            elif kind == "Enum":
                code = "E:" + value["Name"]
            elif kind == "Class":
                code = "C:" + value["Name"]
            else:
                code = value["Name"]
            category = member.get("Category") or "Data"
            if category not in category_index:
                category_index[category] = len(categories)
                categories.append(category)
            flags = READABLE[read]
            if "ReadOnly" in mtags or write == "NotAccessibleSecurity" or (write == "RobloxSecurity" and read != "RobloxSecurity"):
                flags += "r"
            elif RANK.get(write, 0) > RANK.get(read, 0):
                flags += "W"
            flags += "d" if "Deprecated" in mtags else ""
            flags += "h" if "Hidden" in mtags else ""
            flags += "n" if "NotScriptable" in mtags else ""
            flags += "w" if "WriteOnly" in mtags else ""
            name = member["Name"]
            assert "," not in name and ";" not in name and "|" not in name, name
            props.append("%s,%s,%d,%s" % (name, code, category_index[category], flags))
        superclass = cls.get("Superclass") or ""
        if superclass == "<<<ROOT>>>":
            superclass = ""
        classes[cls["Name"]] = "%s|%s|%s" % (superclass, ctags, ";".join(props))

    version = client or dump.get("Version", "?")
    lines = [
        "--[[",
        "\tTungsten · base/data/api",
        "\tBundled Roblox class and property data (no downloads). Generated by",
        "\ttools/make_api.py from the API dump of client version %s." % version,
        "\tDecoded by base/explorer/api, which explains the format.",
        "]]",
        "",
        "return {",
        "\tVersion = %s," % lua_string(str(version)),
        "\tCategories = {",
    ]
    for category in categories:
        lines.append("\t\t%s," % lua_string(category))
    lines.append("\t},")
    lines.append("\tClasses = {")
    for name in sorted(classes):
        lines.append("\t\t[%s] = %s," % (lua_string(name), lua_string(classes[name])))
    lines.append("\t},")
    lines.append("}")
    lines.append("")
    with open(target, "w", encoding="utf-8", newline="\n") as handle:
        handle.write("\n".join(lines))
    print("%d classes, %d categories -> %s" % (len(classes), len(categories), target))


if __name__ == "__main__":
    if len(sys.argv) not in (3, 4):
        print(__doc__)
        sys.exit(1)
    main(sys.argv[1], sys.argv[2], sys.argv[3] if len(sys.argv) == 4 else None)
